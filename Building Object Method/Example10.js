// Example-10: Using all Math object methods

console.log("Value of PI:", Math.PI); // Output: 3.141592653589793
console.log("Square root of 16:", Math.sqrt(16)); // Output: 4
console.log("2 raised to the power of 3:", Math.pow(2, 3)); // Output: 8
console.log("Absolute value of -10:", Math.abs(-10)); // Output: 10
console.log("Rounding 4.7:", Math.round(4.7)); // Output: 5
console.log("Ceiling of 4.2:", Math.ceil(4.2)); // Output: 5
console.log("Floor of 4.8:", Math.floor(4.8)); // Output: 4
console.log("Random number between 0 and 1:", Math.random()); // Output: Random number between 0 and 1
console.log("Sine of PI/2:", Math.sin(Math.PI / 2)); // Output: 1
console.log("Cosine of 0:", Math.cos(0)); // Output: 1  
console.log("Tangent of PI/4:", Math.tan(Math.PI / 4)); // Output: 1
console.log("Natural logarithm of e:", Math.log(Math.E)); // Output: 1
console.log("Exponential of 2:", Math.exp(2)); // Output: 7.3890560989306495
console.log("Sign of -5:", Math.sign(-5)); // Output: -1
console.log("Hypotenuse of 3 and 4:", Math.hypot(3, 4)); // Output: 5
console.log("Truncating 4.9:", Math.trunc(4.9)); // Output: 4
console.log("Cube root of 27:", Math.cbrt(27)); // Output: 3
console.log("Logarithm base 10 of 1000:", Math.log10(1000)); // Output: 3
console.log("Logarithm base 2 of 8:", Math.log2(8)); // Output: 3
console.log("Minimum of (3, 1, 4, 1, 5):", Math.min(3, 1, 4, 1, 5)); // Output: 1
console.log("Maximum of (3, 1, 4, 1, 5):", Math.max(3, 1, 4, 1, 5)); // Output: 5
