/*
TODO: Problem-10: While printing the numbers from 100 to 110 using the while loop, the numbers will be divided by 2.
*/
// Solution:

let i = 100; // Initialize a counter variable starting from 111
while(i <= 110){
    console.log(i / 2); // Log the current value of the counter variable divided by 2 to the console
    i++; // Increment the counter variable by 1
    // The loop will continue until the counter variable is less than or equal to 110
    // This will log the numbers from 111 to 110 divided by 2 to the console
    // The output will be: 55.5, 56, ..., 55
    // The output will be: 55.5, 56, 56.5, ..., 55
}
// The output will be: 55.5, 56, 56.5, ..., 55