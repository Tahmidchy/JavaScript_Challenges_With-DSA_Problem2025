// Solution: 
/*
this কিভাবে নিধারিত হয় তা নির্ভর করে কনটেক্সটের উপর। সাধারণত, this এর মান নির্ধারিত হয় নিম্নলিখিত কনটেক্সট অনুযায়ী:
1. Global Context: যদি কোনো ফাংশন গ্লোবাল কনটেক্সটে কল করা হয়, তাহলে this গ্লোবাল অবজেক্টকে রেফার করে (ব্রাউজারে window, Node.js এ global)।
2. Object Method: যদি কোনো মেথড অবজেক্টের মধ্যে কল করা হয়, তাহলে this সেই অবজেক্টকে রেফার করে।
3. Constructor Function: যদি কোনো ফাংশন new কিওয়ার্ড দিয়ে কল করা হয়, তাহলে this নতুন তৈরি হওয়া অবজেক্টকে রেফার করে।
4. Explicit Binding: bind(), call(), apply() মেথড ব্যবহার করে this কে স্পষ্টভাবে নির্ধারণ করা যায়।
5. Arrow Functions: arrow function এ this লেক্সিক্যাল কনটেক্সট অনুযায়ী নির্ধারিত হয়, অর্থাৎ এটি তার surrounding scope এর this কে রেফার করে। */